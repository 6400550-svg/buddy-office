import Foundation

/// 手绘像素字体：数字和少量英文/符号（1.2M、03:12、2/10、×3、z…）。
/// 中文不走这里，中文用 TextRenderer（苹方）。
public struct PixelFont: Sendable {
    public let name: String
    public let height: Int
    let glyphs: [Character: [String]]   // 每个字符若干行，'#' 有像素
    public let spacing: Int

    public func width(of text: String) -> Int {
        var w = 0
        for (i, ch) in text.enumerated() {
            let g = glyphs[ch] ?? glyphs["?"] ?? []
            w += (g.first?.count ?? 0)
            if i < text.count - 1 { w += spacing }
        }
        return w
    }

    /// text-audit 用：每次 draw 的记录（位置、大小、应该待在哪个矩形里、有没有字符落到了「?」占位字形）。
    public struct DrawRecord: Sendable {
        public var font: String
        public var text: String
        public var rect: IntRect
        public var container: IntRect?
        public var missingGlyph: Bool
        public var spacing: Int
        /// 这次 draw 真正写下的像素（位置 + 写完之后画布上的调色板索引）：最终画面里这些位置的索引变了，说明后画的东西盖住了它。
        public var pixels: [Pixel] = []
        public struct Pixel: Sendable { public var x: Int; public var y: Int; public var idx: UInt16 }
        /// 画在哪块画布上（text-audit 只看画在最终画面那块画布上的；画在草稿 / 哈希用画布上的不算）。
        public var canvasID: ObjectIdentifier
    }
    /// 审计钩子：平时关着（draw 里只读一个 Bool，几乎零开销）；text-audit 渲染时打开，收集这一帧里所有像素字的 draw。
    /// 别的线程同时在画（并行跑的测试）也会被收进来——调用方按 canvasID 过滤；sink 自己要线程安全。
    nonisolated(unsafe) public static var auditEnabled = false
    nonisolated(unsafe) private static var auditSinkStorage: ((DrawRecord) -> Void)? = nil
    private static let auditLock = NSLock()
    public static func setAuditSink(_ sink: ((DrawRecord) -> Void)?) {
        auditLock.lock(); auditSinkStorage = sink; auditEnabled = sink != nil; auditLock.unlock()
    }
    /// draw 里读开关：在锁里读（没锁的读和 setAuditSink 里的写是数据竞争，TSan 抓到过；一次没有争用的 NSLock 约 20 ns，每帧只有几十次 draw）。
    private static func auditActive() -> Bool { auditLock.lock(); defer { auditLock.unlock() }; return auditEnabled }

    public func hasGlyph(_ ch: Character) -> Bool { glyphs[ch] != nil }

    /// 画字。value 是「值」（色阶由 style 决定）。返回画出的宽度。container：这串字应该待在哪个矩形里（只给 text-audit 用）。
    @discardableResult
    public func draw(_ text: String, x: Int, y: Int, value: UInt8, style: Resolved, on canvas: Canvas, id: UInt16 = 0, container: IntRect? = nil) -> Int {
        var cx = x
        var written: [DrawRecord.Pixel] = []
        let audit = Self.auditActive()
        for ch in text {
            let g = glyphs[ch] ?? glyphs["?"] ?? []
            for (ry, row) in g.enumerated() {
                for (rx, c) in row.enumerated() where c == "#" {
                    canvas.set(cx + rx, y + ry, value: value, style: style, id: id)
                    if audit {
                        let px = cx + rx, py = y + ry
                        if px >= 0, py >= 0, px < canvas.width, py < canvas.height { written.append(DrawRecord.Pixel(x: px, y: py, idx: canvas.idx[py * canvas.width + px])) }
                    }
                }
            }
            cx += (g.first?.count ?? 0) + spacing
        }
        let w = cx - x - spacing
        if audit {
            Self.auditLock.lock(); let sink = Self.auditSinkStorage; Self.auditLock.unlock()
            sink?(DrawRecord(font: name, text: text, rect: IntRect(x, y, w, height), container: container,
                             missingGlyph: text.contains { glyphs[$0] == nil }, spacing: spacing, pixels: written, canvasID: ObjectIdentifier(canvas)))
        }
        return w
    }

