/// 用到的角色：s S t 3 = 衣服 高光/基色/阴影/描边；a A u = 点缀色 基色/阴影/高光（衬衫、里层）；
/// j K 2 = 肤色 阴影/基/描边（领口里露出的脖子）；n = 白点（纽扣、拉链头）。
///
/// 通用约定（每件衣服都一样）：
///  · 第 0 行 = 肩线上沿的一行；`neck` = 脖子中心；`shoulderL/R` = 手臂接口，永远在 neck.y + 3 行。
///    有立领的夹克把颈线放在第 1 行（H = 11、neck.y = 1），所以肩、下摆在头下面的绝对位置和别的衣服完全一样。
///  · 手臂（Limbs.drawArm / 手臂精灵）从 shoulderL/R 锚点出发、盖在肩袖那两列上：袖子颜色要和这件衣服的「袖山」一致
///    （见每个 build 函数标题里的说明：vest 是点缀色，其余是衣服色）。
///  · 躯干下半部分会被椅子靠背（背面）或大腿（正面坐姿）盖住 3 行左右，所以身份特征都放在上半身（领口、肩线、后背上部），
///    而且在「长发盖住后领」时还剩两行可见的后背上也放了标志（罗纹 / 工字褶 / 横缝 / 点缀色袖）。
