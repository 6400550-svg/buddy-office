    fileprivate static let outfitAccentMat = Material(hi: Role.accent2, base: Role.accent, sh: Role.accentSh, out: Role.accentSh)

    fileprivate static func addOutfitTorso(_ book: SpriteBook, _ outfit: String, _ facing: String, _ g: Grid,
                                     neck: IntPoint, sl: IntPoint, sr: IntPoint) {
        precondition(g.w == 14, "torso.\(outfit).\(facing) 宽度是 \(g.w)，应为 14")
        book.add(g.sprite(name: "torso.\(outfit).\(facing)", anchors: ["neck": neck, "shoulderL": sl, "shoulderR": sr]))
    }

