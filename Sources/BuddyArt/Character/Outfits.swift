    fileprivate static func outfitLayer(_ rows: String, _ mat: Material = .cloth) -> Grid {
        let b = Bitmap(rows)
        precondition(b.w <= 14, "layer 宽度超过 14")
        return ShadeKit.shade(b, mat)
    }

