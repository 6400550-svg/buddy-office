        ...AAA..AA.A....
        .....A.....A....
        .....A.l..lA....
        ......AA..A.....
        """)
        addAcc(book, "glasses", .side, y0: 9, """
        ..........nA....
        .....AAAAA..A...
        .........A..A...
        .........A.lA...
        ..........AA....
        """)
    }

    // ============ 围巾（躯干上的叠层，14×10）============
    // 第 0 行 = 肩线上沿，和 torso.tee.* 一样：锚点 neck 背面/侧面/正面 (7,0)，3/4 是 (8,0)。
    // 绕脖子一圈（斜条纹）+ 尾巴（横条纹，盖在圈上垂下来，末端流苏）+ 正面的结。
    static func buildScarves(_ book: SpriteBook) {
        func mask14(_ rows: String, _ what: String) -> Bitmap {
            let m = Bitmap(rows)
            precondition(m.w == 14, "\(what) 蒙版宽度是 \(m.w)，应为 14")
            var b = Bitmap(w: 14, h: 10)
            for y in 0..<min(m.h, 10) { for x in 0..<14 where m[x, y] { b[x, y] = true } }
            return b
        }
        /// wrap：绕脖子的圈；tails：每条尾巴一张蒙版（后面的盖在前面的上面）；knot：结。
        /// ring(x, y) 为真的格子是圈上的淡色条，tail(y) 为真的行是尾巴上的淡色条。
        func scarf(_ facing: Facing, neckX: Int, wrap: String, tails: [String], knot: String? = nil,
                   ring: @escaping (Int, Int) -> Bool = { x, y in (x + y) % 3 == 0 }, tail: @escaping (Int) -> Bool = { $0 % 3 == 1 }) {
            let what = "acc.scarf.\(facing.name)"
            var g = Grid(w: 14, h: 10)
            let wm = mask14(wrap, what)
            var wg = ShadeKit.shade(wm, accentMat, hiBand: false)
            for y in 0..<10 { for x in 0..<14 where wm[x, y] && ring(x, y) && wg[x, y] != Role.accentSh { wg[x, y] = Role.accent2 } }
            g.overlay(wg)
            var tailBits = Bitmap(w: 14, h: 10)
            for t in tails {
                let tm = mask14(t, what)
                tailBits = tailBits.union(tm)
                var tg = ShadeKit.shade(tm, accentMat, hiBand: false)
                for y in 0..<10 { for x in 0..<14 where tm[x, y] && tail(y) && tg[x, y] != Role.accentSh { tg[x, y] = Role.accent2 } }
                // 流苏：尾巴最下面一行的下面，隔一列一根
                for x in 0..<14 {
                    var bot = -1
                    for y in 0..<10 where tm[x, y] { bot = y }
                    guard bot >= 0, bot + 1 < 10 else { continue }
                    if x % 2 == 1 { tg[x, bot + 1] = Role.accentSh; if bot + 2 < 10 { tg[x, bot + 2] = Role.accentSh } }
                    else { tg[x, bot + 1] = Role.accent }
                }
                g.overlay(tg)
            }
            if let k = knot {
                let km = mask14(k, what)
                var kg = ShadeKit.shade(km, accentMat)
                for y in 0..<10 { for x in 0..<14 where km[x, y] && kg[x, y] == Role.accent { kg[x, y] = Role.accent2 } }
                g.overlay(kg)
            }
            // 投在衣服上的影子（用衣服的阴影色 t，所以任何衣服都合适）：圈的下缘一行、尾巴右侧一列（光从左上来）
            var shadow = Grid(w: 14, h: 10)
            for x in 0..<14 {
                var yb = -1
                for y in 0..<10 where wm[x, y] { yb = y }
                if yb >= 0 && yb + 1 < 10 && g[x, yb + 1] == 0 { shadow[x, yb + 1] = Role.clothSh }
            }
            for y in 0..<10 { for x in 0..<13 where tailBits[x, y] && g[x + 1, y] == 0 { shadow[x + 1, y] = Role.clothSh } }
            for y in 0..<10 { for x in 0..<14 where shadow[x, y] != 0 && g[x, y] == 0 { g[x, y] = shadow[x, y] } }
            book.add(g.sprite(name: what, anchors: ["neck": IntPoint(neckX, 0)]))
        }
        scarf(.back, neckX: 7, wrap: """
        ...########...
        .############.
        ..##########..
        """, tails: ["""
        ..............
        ..............
        .......###....
        .......###....
        .......###....
        .......###....
        .......###....
        .......###....
        """])
        scarf(.threeQuarterBack, neckX: 8, wrap: """
        ....########..
        ..###########.
        ...##########.
        """, tails: ["""
        ..............
        ..............
        ........###...
        ........###...
        ........###...
        ........###...
        ........###...
        ........###...
        """])
        scarf(.side, neckX: 7, wrap: """
        ....######....
        ...########...
        ...########...
        """, tails: ["""
        ..............
        ..............
        ...###........
        ...###........
        ...###........
        ...###........
        ...###........
        ...###........
        """, """
        ..............
        ..............
        ........##....
        ........##....
        ........##....
        ........##....
        ..............
        ..............
        """])
        scarf(.threeQuarterFront, neckX: 8, wrap: """
        ...########...
        .############.
        ..##########..
        """, tails: ["""
        ..............
        ..............
        ..............
        .......###....
        .......###....
        .......###....
        .......###....
        .......###....
        """], knot: """
        ..............
        ..............
        ......####....
        ......####....
        """)
        scarf(.front, neckX: 7, wrap: """
        ...########...
        .############.
        ..##########..
        """, tails: ["""
        ..............
        ..............
        ..............
        .......###....
        .......###....
        .......###....
        .......###....
        .......###....
        """], knot: """
        ..............
        ..............
        ......####....
        ......####....
        """)
    }
}
