extension CharacterArt {
    // MARK: 配饰
    //
    // acc.<配饰>.<朝向>：
    //  · headphones / beanie / hairpin（5 个朝向）、glasses（front / q34front / side）：头上的配饰，和头发共用 16×20 的画布，
    //    头盒子左上角在 hairPad = (2,3)，锚点 head = hairPad；渲染时和头发一样贴（画在头发之后）。
    //  · scarf（5 个朝向）：躯干上的叠层，14×10，第 0 行 = 肩线上沿，锚点 neck = (7,0)（3/4 是 (8,0)），和 torso.tee.* 一致；
    //    画在躯干和头之后，位置和躯干一样（让 scarf 的 neck 锚点落在躯干的 neck 锚点上）。
    // 下面的 ASCII 直接按「画布坐标」写（16 列，第 0 列 = 画布最左；头盒子第 x 列 = 画布第 x+2 列），rows 的第一行对应画布第 y0 行。
    // 字符：a 点缀  A 点缀影（最深的点缀色）  u 点缀高光  n 白点  l 镜片  t 衣服阴影（围巾投在衣服上的影子）。
    // 全部只用点缀色三级（u/a/A）+ n、l，没有写死颜色。

    /// 逐行检查过宽度的 16 列 ASCII → 16×20 格子（第一行对应画布第 y0 行）。
    private static func accRows(_ rows: String, y0: Int, _ what: String) -> Grid {
        var ls = rows.split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
        while let f = ls.first, f.trimmingCharacters(in: .whitespaces).isEmpty { ls.removeFirst() }
        while let l = ls.last, l.trimmingCharacters(in: .whitespaces).isEmpty { ls.removeLast() }
        var g = Grid(w: hairW, h: hairH)
        for (i, l) in ls.enumerated() {
            let t = l.trimmingCharacters(in: .whitespaces)
            precondition(t.count == hairW, "\(what) 第 \(y0 + i) 行宽度是 \(t.count)，应为 \(hairW)：\(t)")
            precondition(y0 + i < hairH, "\(what) 行数超出")
            for (x, c) in t.enumerated() where c != "." {
                guard let r = Role.chars[c] else { preconditionFailure("\(what) 里有不认识的字符「\(c)」") }
                g[x, y0 + i] = r
            }
        }
        return g
    }

    private static func addAcc(_ book: SpriteBook, _ name: String, _ facing: Facing, y0: Int, _ rows: String) {
        let what = "acc.\(name).\(facing.name)"
        book.add(accRows(rows, y0: y0, what).sprite(name: what, anchors: ["head": hairPad]))
    }

    static func buildAccessories(_ book: SpriteBook) {
        buildHeadphones(book)
        buildBeanies(book)
        buildHairpins(book)
        buildGlasses(book)
        buildScarves(book)
    }

    // 点缀色的三级材质：高光 u / 基色 a / 阴影 A（选择性描边：左上边用基色，右下边用 A）。
    private static let accentMat = Material(hi: Role.accent2, base: Role.accent, sh: Role.accent, out: Role.accentSh)

    /// 16 列 '#' 蒙版（第一行对应画布第 y0 行）→ 16×20 位图。
    private static func accBits(_ rows: String, y0: Int, _ what: String) -> Bitmap {
        let m = Bitmap(rows)
        precondition(m.w == hairW, "\(what) 蒙版宽度是 \(m.w)，应为 \(hairW)")
        var b = Bitmap(w: hairW, h: hairH)
        for y in 0..<m.h { for x in 0..<m.w where m[x, y] { b[x, y0 + y] = true } }
        return b
    }

