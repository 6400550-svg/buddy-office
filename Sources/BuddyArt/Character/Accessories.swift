extension CharacterArt {
    // ============ 毛线帽 ============
    // 轮廓（蒙版）比头发大一圈；每一列最下面 cuffRows 格是翻边（竖罗纹），上面是帽身（淡淡的竖纹）。
    // 帽顶有一个白色的小绒球（rows 0–4，下面两行盖在帽顶上）。
    static func buildBeanies(_ book: SpriteBook) {
        func beanie(_ facing: Facing, ribCenter: Double = 7.5, sil: String, cuffRows: Int = 3) {
            let what = "acc.beanie.\(facing.name)"
            let all = accBits(sil, y0: 4, what)
            var dome = Bitmap(w: hairW, h: hairH), cuff = Bitmap(w: hairW, h: hairH)
            var bottoms = [Int](repeating: -1, count: hairW)
            for x in 0..<hairW { for y in 0..<hairH where all[x, y] { bottoms[x] = y } }
            for x in 0..<hairW where bottoms[x] >= 0 {
                for y in 0..<hairH where all[x, y] {
                    if y > bottoms[x] - cuffRows { cuff[x, y] = true } else { dome[x, y] = true }
                }
            }
            var g = ShadeKit.shade(dome, accentMat)
            // 帽身的竖罗纹：几条隔行的阴影短线
            let shift = Int((ribCenter - 7.5).rounded(.up))
            for y in 5..<hairH { for x in [4, 6, 9, 11].map({ $0 + shift }) where x >= 0 && x < hairW && dome[x, y] && g[x, y] == Role.accent { g[x, y] = Role.accentSh } }
            var c = Grid(w: hairW, h: hairH)
            for x in 0..<hairW where bottoms[x] >= 0 {
                for y in 0..<hairH where cuff[x, y] {
                    let top = y == bottoms[x] - cuffRows + 1, bot = y == bottoms[x]
                    if bot { c[x, y] = Role.accentSh }
                    else if top { c[x, y] = x % 2 == 0 ? Role.accent2 : Role.accent }
                    else { c[x, y] = x % 2 == 0 ? Role.accent : Role.accentSh }
                }
            }
            g.overlay(c)
            // 绒球：6×5，白色（n）的毛球，坐在帽顶正中（下面两行盖在帽顶上）；左上边缘用点缀高光，右下用点缀色，几点毛茸茸的杂色
            g.overlay(accRows("""
            ......uuua......
            .....unnnna.....
            .....unnnuA.....
            .....unnuuA.....
            ......AAAA......
            """, y0: 0, what))
            book.add(g.sprite(name: what, anchors: ["head": hairPad]))
        }
        beanie(.back, sil: """
        ...##########...
        ..############..
        .##############.
        .##############.
        .##############.
        .##############.
        .##############.
        ...##########...
        """)
        beanie(.threeQuarterBack, ribCenter: 8, sil: """
        ...##########...
        ..############..
        .##############.
        .##############.
        .##############.
        .##############.
        .###########....
        ...########.....
        """)
        beanie(.side, ribCenter: 8.5, sil: """
        ...##########...
        ..############..
        .##############.
        .##############.
        .##########.....
        .#######........
        .####...........
        .##.............
        """)
        beanie(.threeQuarterFront, ribCenter: 8, sil: """
        ...##########...
        ..############..
        .##############.
        .##############.
        .############...
        .#######........
        .###............
        """)
        beanie(.front, sil: """
        ...##########...
        ..############..
        .##############.
        .##############.
        ..############..
        """, cuffRows: 2)
    }
}

extension CharacterArt {
    // ============ 发夹（蝴蝶结）============
    static func buildHairpins(_ book: SpriteBook) {
        // 蝴蝶结 6×4：外端高、中间窄（像领结），中间一个深色的结；左上一点高光，右下阴影。
        // 夹在 buddy 的「右手边」：背面/3/4 背面在画面右侧（后脑右侧），侧面在耳朵上方，3/4 正面/正面在画面左侧的刘海上——
        // 这样从背面转到正面时，蝴蝶结跟着头一起转过去，不会跳到另一边。
        //      0123456789012345
        for f in [Facing.back, .threeQuarterBack] {
            addAcc(book, "hairpin", f, y0: 6, """
            .......na...a...
            .......aaAAaa...
            .......aaAAaA...
            .......aA...A...
            """)
        }
        addAcc(book, "hairpin", .side, y0: 5, """
        .....na...a.....
        .....aaAAaa.....
        .....aaAAaA.....
        .....aA...A.....
        """)
        for f in [Facing.threeQuarterFront, .front] {
            addAcc(book, "hairpin", f, y0: 5, """
            ...na...a.......
            ...aaAAaa.......
            ...aaAAaA.......
            ...aA...A.......
            """)
        }
    }

    // ============ 眼镜（front / q34front / side）============
    static func buildGlasses(_ book: SpriteBook) {
        addAcc(book, "glasses", .front, y0: 9, """
