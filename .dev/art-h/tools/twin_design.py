def ball5(x0, ytop=-2):
    """5×4 的团子（x0 是最左列）：圆角，底下一行 3 宽压在头上"""
    px=set()
    for x in range(x0+1,x0+4): px.add((x,ytop))
    for y in (ytop+1,ytop+2):
        for x in range(x0,x0+5): px.add((x,y))
    for x in range(x0+1,x0+4): px.add((x,ytop+3))
    return px

NOTES={'back':'背面：头顶两侧各一个团子（5×4，压在头顶角上，内部有描边），点缀色发圈；发盖住整个后脑，亮线通向左团子、暗线通向右团子',
 'q34back':'3/4 背面：右团子向右移 1 格（近侧），右侧第 10–11 列第 8–10 行留给耳朵和脸颊',
 'side':'侧面：只见近侧一个团子，在头顶靠后；耳朵露出来',
 'q34front':'3/4 正面：两个团子探出刘海上方',
 'front':'正面：左右对称两个团子，刘海参差，额头上有一点肤色阴影 (j)'}
def build(facing, mask, balls, ties, extra=None):
    s=Spr('twinBuns',facing,mask,note=NOTES[facing])
    for b in balls: sphere_part(s,b,hi_t=-0.3,sh_t=0.2)
    for (k,v) in list(s.paint.items()):
        if v=='h' and k[1]<=-1 and facing in ('back','q34back'): s.paint[k]='r'
    for t in ties: s.stamp(t,force=True)
    if facing in ('back','q34back'):
        for (x,y) in ((2,-2),(3,-2)): pass
        s.stamp('-2@2| r',force=True)
        s.stamp('-2@%d| r'%(9 if facing=='q34back' else 8),force=True)
    if extra: extra(s)
    return s

