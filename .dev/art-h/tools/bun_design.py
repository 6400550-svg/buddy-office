#!/usr/bin/env python3
import os
from hp import *
SP=os.environ['SP']
sprites=[]

DOME_BACK='''2@2| ########
3@1| ##########
4@1| ##########
5@1| ##########
6@1| ##########
7@0| ############
8@0| ############
9@0| ############
10@1| ##########
11@1| ####..####
12@2| ##....##'''
DOME_Q34B='''2@2| ########
3@1| ##########
4@1| ##########
5@1| ##########
6@1| ##########
7@0| ############
8@0| ##########
9@0| ##########
10@1| #########
11@1| ####..###
12@2| ##....#'''

def ball(s, x0):
    """球 4/6/8/8 宽 + 6 宽的发圈（点缀色）；x0 = 球最左一列（中间两行的 x）"""
    s.stamp(f'-2@{x0+2}| rrHg')
    s.stamp(f'-1@{x0+1}| hHgHHg')
    s.stamp(f'0@{x0+1}| HgHHgg')
    s.stamp(f'1@{x0+1}| uaaaaA', force=True)
    s.stamp(f'-3@{x0+3}| rr', force=True)

def dome(s, cx):
    s.stamp('2@%d| hhgggg'%(cx-3))
    s.pts([(cx-4,3),(cx-3,3),(cx-4,4)],'h')                                   # 亮月牙
    s.pts([(cx-2,3),(cx-2,4),(cx-3,5),(cx-3,6),(cx-3,7)],'h')                 # 亮线（向球收拢）
    s.pts([(cx+1,3),(cx+1,4),(cx+2,5),(cx+2,6),(cx+2,7)],'g')                # 暗线

def ballmask(x0, y_rows=(-3,-2,-1,0,1)):
    """球的蒙版行：-3: 4 宽，-2: 6 宽，-1/0: 8 宽，1: 6 宽（发圈）。x0=最左"""
    return f'''-3@{x0+2}| ####
-2@{x0+1}| ######
-1@{x0}| ########
0@{x0}| ########
1@{x0+1}| ######'''

# ---------------- 背面 ----------------
s=Spr('bun','back',ballmask(2)+'\n'+DOME_BACK,note='背面：头顶正中一个大球（最宽 8 格）+ 点缀色发圈（6 宽）；发盖住整个后脑，发丝向球收拢，左上亮线、右下暗线；后颈发际线中间留缺口')
ball(s,2); dome(s,6)
sprites.append(s)
# ---------------- 3/4 背面 ----------------
s=Spr('bun','q34back',ballmask(1)+'\n'+DOME_Q34B,note='3/4 背面：球随头转向左移 1 格；右侧第 10–11 列第 8–10 行留给耳朵和脸颊')
ball(s,1); dome(s,5)
sprites.append(s)
# ---------------- 侧面：球在脑后偏上 ----------------
m='''-3@1| ####
-2@0| ######
-1@0| #######
0@0| #######
1@1| #####
2@1| #########
3@1| ##########
4@1| ##########
5@1| ########
6@1| ######
7@1| ######
8@1| ##..#
9@1| ##
10@1| ##
11@2| ##'''
s=Spr('bun','side',m,note='侧面：球在脑后偏上（发圈朝向脑后），耳朵 (3–4, 8–10) 露出来，额前一小绺刘海')
s.stamp('-2@2| rHg\n-1@1| hHgHg\n0@1| HgHgg')
s.stamp('1@1| uaaAA',force=True)
s.stamp('-3@2| rr',force=True)
s.stamp('2@1| hhgggg')
s.pts([(2,3),(3,3),(2,4)],'h')
s.pts([(9,3),(8,3),(7,3),(6,3),(5,4),(4,5),(3,6)],'g')
sprites.append(s)
# ---------------- 3/4 正面 ----------------
m=ballmask(1)+'''
2@2| ########
3@1| ##########
4@1| ##########
5@1| #####.####
6@1| ##.......#
7@1| ##.......#
8@1| #'''
s=Spr('bun','q34front',m,note='3/4 正面：球探出刘海上方；刘海在额头上投一点肤色阴影 (j)')
ball(s,1); dome(s,5)
s.stamp('5@6| j',free=True)
s.stamp('6@1| gH\n7@1| gH\n8@1| g',force=True)
sprites.append(s)
# ---------------- 正面 ----------------
m=ballmask(2)+'''
2@2| ########
3@1| ##########
4@1| ##########
5@1| ####.##..#
6@1| #........#
7@1| #........#
8@1| #........#'''
s=Spr('bun','front',m,note='正面：球探出刘海上方；两侧一缕鬓发，耳朵露出来')
ball(s,2); dome(s,6)
s.stamp('5@5| j\n5@8| jj',free=True)
s.stamp('6@1| g\n7@1| g\n8@1| g',force=True)
sprites.append(s)
write_style(SP+'/styles/bun.swift','buildBun','单丸子头 bun',sprites)
print('bun written')
